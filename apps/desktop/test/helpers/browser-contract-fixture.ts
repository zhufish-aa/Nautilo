import assert from "node:assert/strict";
import { app,BrowserWindow,WebContentsView,session } from "electron";
import { createServer } from "node:http";
import { createHmac } from "node:crypto";
import { readFile,writeFile } from "node:fs/promises";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { TaskBrowser } from "../../src/main/task-browser";
import { browserDeadline,browserError } from "../../src/main/browser-errors";
import { browserLogin } from "../../src/main/browser-login";

const root=__dirname;
app.setPath("userData",root);app.setPath("sessionData",root);app.setAppLogsPath(root);
app.commandLine.appendSwitch("remote-debugging-port","0");
let phase="startup";
const checkpoint=(value:string)=>{phase=value;writeFileSync(join(root,"contract-phase.txt"),value);};
void app.whenReady().then(async()=>{
  const site=createServer((req,res)=>{
    if(req.url === "/download"){res.writeHead(200,{"Content-Type":"application/octet-stream","Content-Disposition":"attachment; filename=proof.txt"});res.end("browser-download-proof");return;}
    res.writeHead(200,{"Content-Type":"text/html"}).end(`<!doctype html><title>Contract test</title><main id="scope"><label>Query<input id="query"></label><a href="#one" id="one">Choice</a><a href="#two" id="two">Choice</a><input id="file" type="file"><button id="prompt" onclick="document.body.dataset.reply=prompt('Name?')">Prompt</button><div id="outside">Body</div></main><button id="not-scope">Outside</button>`);
  });
  await new Promise<void>(resolve=>site.listen(0,"127.0.0.1",resolve));
  const url="http://127.0.0.1:"+(site.address() as {port:number}).port;
  const browser=new TaskBrowser(), key="contract-fixture";
  const port=await browser.start(()=>key);
  const owner=new BrowserWindow({show:false,opacity:0,skipTaskbar:true,webPreferences:{sandbox:true}});
  await owner.loadURL("about:blank");browser.attachWindow(owner);
  let calls=0;
  const call=async(name:string,args:any={},id="One")=>{
    calls++;
    const token=createHmac("sha256",key).update(`nautilo-browser-v1/${port}/${id}`).digest("base64url");
    const response=await fetch(`http://127.0.0.1:${port}/mcp/${id}`,{method:"POST",headers:{authorization:"Bearer "+token,"content-type":"application/json"},body:JSON.stringify({jsonrpc:"2.0",id:calls,method:"tools/call",params:{name,arguments:args}})});
    const result=(await response.json()).result;
    return result.structuredContent ?? JSON.parse(result.content.at(-1).text);
  };
  const ok=async(name:string,args:any={},id="One")=>{const result=await call(name,args,id);assert.notEqual(result.ok,false,JSON.stringify(result));return result;};
  await ok("browser_run",{steps:[{action:"goto",url}],snapshot:false});
  const group=browser["groups"].get("One")!,page=group.tabs.get(group.agent!)!,wc=page.view.webContents;
  checkpoint("timeout aliases and matched sample");
  const immediate=await ok("browser_eval",{script:"() => ({n:3})",expect:{n:{gt:0}},timeoutMs:4000});
  assert.equal(immediate.steps[0].verification.attempts,1);
  const polled=await ok("browser_eval",{script:"() => ({n:performance.now()})",expect:{n:{gt:(await wc.executeJavaScript("performance.now()"))+450}},timeoutMs:4000});
  assert.ok(polled.steps[0].verification.attempts>1);
  assert.equal(polled.value.n,polled.steps[0].verification.actual.eval.n);
  const batch=await ok("browser_run",{steps:[{action:"eval",script:"() => ({n:performance.now()})",expect:{n:{gt:(await wc.executeJavaScript("performance.now()"))+350}},timeoutMs:4000}],snapshot:false});
  assert.ok(batch.steps[0].verification.attempts>1);
  assert.equal(batch.steps[0].result.n,batch.steps[0].verification.actual.eval.n);
  assert.equal((await call("browser_eval",{script:"1",timeoutMs:500,timeout_ms:600})).error.code,"INVALID_FIELD");
  checkpoint("nth, scoped refs and safe rebind");
  await ok("browser_run",{steps:[{action:"click",target:{css:"a",nth:0}},{action:"click",target:{css:"a",nth:-1}}],snapshot:false});
  assert.match(wc.getURL(),/#two$/);
  assert.equal((await call("browser_run",{steps:[{action:"click",target:{css:"a",nth:30}}],snapshot:false})).error.code,"target_not_found");
  const view=await ok("browser_read",{format:"refs",root:"#scope",scope:"document",limit:2});
  assert.equal(view.refs.length,2);assert.equal(view.truncated,true);assert.equal(view.next_offset,2);
  const continuation=await ok("browser_read",{format:"refs",root:"#scope",scope:"document",limit:2,offset:2,view_id:view.view_id});
  assert.notEqual(continuation.refs[0].ref,view.refs[0].ref);
  const all=await ok("browser_read",{format:"refs",root:"#scope",scope:"document",limit:100});
  assert.ok(!all.refs.some((ref:any)=>ref.name === "Outside"));
  const ref=all.refs.find((ref:any)=>ref.name === "Query").ref;
  await wc.executeJavaScript("document.querySelector('#query').replaceWith(document.querySelector('#query').cloneNode())");
  const rebound=await ok("browser_run",{steps:[{action:"fill",target:{ref,view_id:all.view_id},text:"rebound"}],snapshot:false});
  assert.equal(await wc.executeJavaScript("document.querySelector('#query').value"),"rebound");
  assert.equal(rebound.steps[0].ref_rebound,true);
  checkpoint("no model-facing favicon payload; scoped CDP");
  page.favicon="data:image/png;base64,"+"A".repeat(32000);
  assert.ok(!JSON.stringify(await ok("browser_session",{action:"list"})).includes("data:image"));
  assert.ok(!JSON.stringify(await ok("browser_tabs",{action:"list"})).includes("data:image"));
  const cdp=await ok("browser_cdp",{method:"Runtime.evaluate",params:{expression:"document.title",returnByValue:true}});
  assert.equal(cdp.result.result.value,"Contract test");
  assert.equal((await call("browser_cdp",{method:"Target.getTargets"})).error.code,"INVALID_CDP_METHOD");
  checkpoint("dialog arm and actual native result");
  await ok("browser_dialog",{action:"arm",accept:true,prompt_text:"Nautilo"});
  await ok("browser_run",{steps:[{action:"click",target:{css:"#prompt"},expect:{event:{method:"Page.javascriptDialogOpening"}}}],snapshot:false});
  assert.equal(await wc.executeJavaScript("document.body.dataset.reply"),"Nautilo");
  checkpoint("file chooser upload and download save");
  const upload=join(root,"upload.txt");await writeFile(upload,"input-proof");
  await ok("browser_files",{action:"arm_chooser"});
  await ok("browser_run",{steps:[{action:"click",target:{css:"#file"},expect:{event:{type:"filechooser"}}}],snapshot:false});
  await ok("browser_files",{action:"upload",paths:[upload]});
  assert.equal(await wc.executeJavaScript("document.querySelector('#file').files[0].name"),"upload.txt");
  const download=await ok("browser_files",{action:"download",url:url+"/download"});
  const saved=join(root,"saved-proof.txt");
  await ok("browser_files",{action:"save",download_id:download.download_id,path:saved});
  assert.equal(await readFile(saved,"utf8"),"browser-download-proof");
  assert.equal((await call("browser_files",{action:"save",download_id:download.download_id,path:saved})).error.code,"SAVE_FAILED");
  assert.equal((await call("browser_files",{action:"save",download_id:download.download_id,path:join(root,"stolen.txt")},"Other")).error.code,"DOWNLOAD_NOT_FOUND");
  checkpoint("named spaces and origin-bounded cookie import");
  const space=await ok("browser_session",{action:"open",name:"Research",url});
  assert.notEqual(space.space_id,"One");
  assert.equal((await ok("browser_session",{action:"open",name:"Research"})).space_id,space.space_id);
  assert.equal((await call("browser_session",{action:"open",name:"Research"},"Other")).error.code,"SESSION_CONFLICT");
  assert.equal((await call("browser_read",{space_id:space.space_id},"Other")).error.code,"SESSION_CONFLICT");
  const source=new WebContentsView({webPreferences:{partition:"persist:source-browser",sandbox:true}});
  await source.webContents.loadURL(url+"/source");
  await source.webContents.session.cookies.set({url,name:"proof_login",value:"synthetic-source-secret",expirationDate:Date.now()/1000+3600});
  let debugPort="";
  for(let i=0;i<30&&!debugPort;i++){debugPort=(await readFile(join(root,"DevToolsActivePort"),"utf8").catch(()=>"")).split("\n")[0];if(!debugPort)await new Promise(resolve=>setTimeout(resolve,100));}
  assert.ok(debugPort);
  const endpoint="http://127.0.0.1:"+debugPort;
  const inspected=await browserLogin(session.fromPartition("persist:nautilo-browser"),"inspect",{endpoint});
  const sourceTarget=inspected.sites!.find((site:any)=>site.url.endsWith("/source"));assert.ok(sourceTarget);
  const imported=await browserLogin(session.fromPartition("persist:nautilo-browser"),"import",{endpoint,target_id:sourceTarget.target_id,origins:[url]});
  assert.ok(imported.imported_cookies!>0);
  assert.ok(!JSON.stringify(imported).includes("synthetic-source-secret"));
  assert.equal((await session.fromPartition("persist:nautilo-browser").cookies.get({url,name:"proof_login"}))[0].value,"synthetic-source-secret");
  source.webContents.close();
  checkpoint("explicit takeover only; ordinary input does not change control");
  const motionThreshold=(await wc.executeJavaScript("performance.now()"))+350;
  const motionBatch=call("browser_run",{steps:[
    {action:"assert",expect:{eval:{script:"() => performance.now()",expect:{$:{gt:motionThreshold}}}}},
    ...Array.from({length:5},()=>({action:"eval",script:"() => document.title"}))
  ],snapshot:false});
  wc.emit("input-event",{} as Electron.Event,{type:"mouseMove",x:20,y:20});wc.focus();
  assert.notEqual((await motionBatch).ok,false);
  const interrupted=call("browser_run",{steps:[{action:"assert",expect:{eval:{script:"() => false"}},timeoutMs:5000},{action:"click",target:{css:"#one"}}],snapshot:false});
  await new Promise(resolve=>setTimeout(resolve,100));wc.emit("input-event",{} as Electron.Event,{type:"mouseDown",x:700,y:250});
  assert.equal(page.manual,false);
  wc.emit("will-navigate",{preventDefault(){}} as Electron.Event,"nautilo-control://"+page.controlKey+"/takeover");
  const paused=await interrupted;assert.equal(paused.status,"paused");assert.equal(paused.control.kind,"takeover_button");assert.deepEqual(paused.remaining_steps,[2]);
  await ok("browser_read",{scope:"main"});browser["changeControl"](group,page,"agent");
  checkpoint("timeout context, receipt v2 and close-last-window");
  const blockedEval=await call("browser_eval",{contract_version:2,script:"() => { const t=Date.now(); while(Date.now()-t<6000){} return {done:true}; }",timeoutMs:500});
  assert.equal(blockedEval.error.code,"OPERATION_TIMEOUT",JSON.stringify(blockedEval));
  assert.equal(blockedEval.error.details.timeout_class,"eval");assert.equal(blockedEval.error.details.timeout_ms,500);
  assert.equal(typeof blockedEval.error.details.renderer_alive,"boolean");
  const timeout=await browserDeadline(new Promise(()=>{}),100,"read document text").catch(browserError);
  assert.equal(timeout.timeout_ms,100);assert.equal(timeout.timeout_class,"read");assert.ok(timeout.elapsed_ms>=90);
  const strict=await ok("browser_eval",{contract_version:2,script:"() => 2",expect:{$:2},timeoutMs:500});
  assert.equal(strict.version,2);assert.equal(strict.data.value,2);assert.equal(strict.steps[0].verification.attempts,1);
  const strictFailure=await call("browser_run",{contract_version:2,steps:[{action:"click",target:{css:"a"}}],snapshot:false});
  assert.equal(strictFailure.error.code,"TARGET_AMBIGUOUS");
  const first=new BrowserWindow({show:false}),second=new BrowserWindow({show:false});
  browser.attachPanelWindow("One",first);browser.attachPanelWindow(space.space_id,second);
  first.close();assert.notEqual(group.suspended,true);
  await ok("browser_eval",{script:"() => 7"});
  const pending=call("browser_run",{steps:[{action:"assert",expect:{url:{includes:"never-match"}},timeoutMs:15000},{action:"click",target:{css:"#one"}}],snapshot:false});
  await new Promise(resolve=>setTimeout(resolve,150));second.close();
  const stopped=await pending;assert.equal(stopped.status,"paused");assert.equal(stopped.error.code,"BROWSER_CLOSED");assert.deepEqual(stopped.remaining_steps,[2]);
  assert.equal((await ok("browser_eval",{script:"() => 8",controlTimeoutMs:0})).value,8,"the next call resumes after a window close");
  checkpoint("real blocked renderer is recovered once without replaying actions");
  browser["changeControl"](group,page,"agent");
  await ok("browser_run",{steps:[{action:"goto",url}],snapshot:false},"Hung");
  const hungGroup=browser["groups"].get("Hung")!,hungPage=hungGroup.tabs.get(hungGroup.agent!)!;
  let reloads=0;hungPage.view.webContents.on("did-start-loading",()=>reloads++);
  await ok("browser_eval",{script:"() => {setTimeout(()=>{while(true){}},30);return 'armed';}"},"Hung");
  await new Promise(resolve=>setTimeout(resolve,80));
  const recovered=await call("browser_read",{scope:"main",limit:256},"Hung");
  assert.equal(recovered.error.code,"RENDERER_UNRESPONSIVE");assert.equal(recovered.error.recovered,true);assert.equal(reloads,1);
  await ok("browser_read",{scope:"main",limit:256},"Hung");
  await writeFile(join(root,"contract-results.json"),JSON.stringify({calls,strict,strictFailure}));
  await browser.close();owner.destroy();await new Promise<void>(resolve=>site.close(()=>resolve()));app.exit(0);
}).catch(error=>{writeFileSync(join(root,"contract-error.txt"),phase+"\n"+(error.stack??String(error)));app.exit(1);});

process.on("uncaughtException",error=>{require("node:fs").writeFileSync(require("node:path").join(__dirname,"contract-error.txt"),error.stack??String(error));app.exit(1);});
